#!/usr/bin/env python3
"""Derive an objective retrieval ground-truth set from a repository's git history.

    python tests/eval/gen_queries.py --repo . --out tests/eval/queries/self_repo_git.yml

Why git history
---------------
Hand-written query sets are small and expensive; sets generated by the retriever
grade its own homework. A commit is neither: a human wrote the subject line
("tolerate missing FastMCP type export") *and*, independently, changed a specific
set of files. That pairing is exactly the agent question we care about — "given a
description of a change, which files implement it?" — and it is recorded before
this tool exists.

Leakage properties
------------------
The query text lives in git metadata, not in the indexed corpus, so unlike
docstring-derived benchmarks (CodeSearchNet-style) the answer is not copied into
the document being retrieved. The one exception is changelog-style files, which
routinely paraphrase commit subjects; they are excluded both as corpus documents
(`CHANGELOG_EXCLUDES`) and as expected answers.

Filtering
---------
Commits survive only if they look like a *localised, described* change:

* not a merge, revert, release, version bump, or pure-formatting commit;
* subject carries at least ``--min-words`` content words after the
  Conventional Commits ``type(scope):`` prefix is stripped;
* touches between 1 and ``--max-files`` files that still exist at HEAD and are
  plausibly indexable source or prose;
* does not touch benchmark scaffolding (which would grade itself).

Duplicate subjects collapse to their first occurrence, so a repeated
"fix lint" contributes one query, not thirty.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path

# Conventional Commits prefix: `type`, optional `(scope)`, optional `!`, colon.
_PREFIX_RE = re.compile(r"^\s*(?P<type>[a-z]+)\s*(?:\((?P<scope>[^)]*)\))?\s*!?\s*:\s*", re.I)

# Subjects that describe bookkeeping rather than a locatable code change.
_SKIP_SUBJECT_RE = re.compile(
    r"^\s*(?:"
    r"merge\b|revert\b|release\b|bump\b|"
    r"v?\d+\.\d+(?:\.\d+)?\s*$|"
    r"(?:chore|style|ci|build|deps)\s*(?:\([^)]*\))?\s*:\s*(?:bump|format|lint|typo|whitespace)"
    r")",
    re.I,
)

# Conventional type -> eval category. Unlisted types fall back to "change".
_TYPE_CATEGORY = {
    "feat": "feature",
    "fix": "bug",
    "perf": "perf",
    "refactor": "refactor",
    "test": "test",
    "docs": "docs",
}

# Files that may be *changed* by a commit but are never a useful retrieval answer.
_ANSWER_DENY_RE = re.compile(
    r"(?:^|/)(?:"
    r"CHANGELOG[^/]*|CHANGES[^/]*|HISTORY[^/]*|NEWS[^/]*|RELEASE[_-]?NOTES[^/]*|"
    r"package-lock\.json|yarn\.lock|poetry\.lock|Cargo\.lock|requirements\.lock|"
    r"go\.sum|Gemfile\.lock|pnpm-lock\.yaml"
    r")$",
    re.I,
)

# Extensions worth retrieving. Binary assets and generated bundles are excluded so
# an image-only commit does not become an unanswerable query.
_ANSWER_EXTS = frozenset(
    """
    py pyi js mjs cjs jsx ts tsx java kt kts go rs rb php cs c h cc cpp hpp
    swift scala clj ex exs erl hs ml dart lua r sql sh bash ps1 psm1
    md rst txt adoc yml yaml toml json xml gradle cfg ini
    """.split()
)

# Benchmark scaffolding: a commit touching it must not become a benchmark query.
_SCAFFOLD_RE = re.compile(r"(?:^|/)tests/(?:eval|benchmark_)", re.I)

# Corpus documents that paraphrase commit subjects. `harness.build_corpus_index`
# applies these on top of its own excludes for every corpus, so a changelog can
# never be the top lexical hit for a query that is literally its own line item.
CHANGELOG_EXCLUDES = (
    "CHANGELOG*", "CHANGES*", "HISTORY*", "NEWS*", "RELEASE_NOTES*", "RELEASE-NOTES*",
    "**/CHANGELOG*", "**/CHANGES*", "**/HISTORY*", "**/NEWS*",
)

_WORD_RE = re.compile(r"[A-Za-z][A-Za-z0-9_-]*")


def _git(repo: Path, *args: str) -> str:
    proc = subprocess.run(
        ["git", "-C", str(repo), *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if proc.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {proc.stderr.strip()}")
    return proc.stdout


def strip_prefix(subject: str) -> tuple[str, str]:
    """Split a Conventional Commits subject into (category, human text)."""
    match = _PREFIX_RE.match(subject)
    if not match:
        return "change", subject.strip()
    rest = subject[match.end():].strip()
    return _TYPE_CATEGORY.get(match.group("type").lower(), "change"), rest


def _is_answerable(path: str) -> bool:
    if _ANSWER_DENY_RE.search(path) or _SCAFFOLD_RE.search(path):
        return False
    ext = path.rsplit(".", 1)[-1].lower() if "." in path.rsplit("/", 1)[-1] else ""
    return ext in _ANSWER_EXTS


def harvest(
    repo: Path,
    *,
    max_commits: int,
    max_files: int,
    min_words: int,
) -> list[dict]:
    """Return ground-truth records mined from `repo`'s history, newest first."""
    tracked = {p for p in _git(repo, "ls-files").splitlines() if p}
    # `%x00` separates subject from the name-only file list without colliding with
    # either; commit records are separated by a sentinel line.
    raw = _git(
        repo,
        "log",
        "--no-merges",
        f"--max-count={max_commits}",
        "--name-only",
        "--pretty=format:%x01%H%x00%s",
        "--diff-filter=ACMR",
    )

    seen_subjects: OrderedDict[str, dict] = OrderedDict()
    for record in raw.split("\x01"):
        record = record.strip("\n")
        if not record:
            continue
        header, _, body = record.partition("\n")
        sha, _, subject = header.partition("\x00")
        subject = subject.strip()
        if not subject or _SKIP_SUBJECT_RE.match(subject):
            continue

        files = [line.strip() for line in body.splitlines() if line.strip()]
        if any(_SCAFFOLD_RE.search(f) for f in files):
            continue
        answers = sorted({f for f in files if f in tracked and _is_answerable(f)})
        if not answers or len(answers) > max_files:
            continue

        category, text = strip_prefix(subject)
        # Backticks and quotes in subjects are prose decoration, not query intent.
        # Collapse the resulting gaps so the query reads like something a user typed.
        text = " ".join(text.replace("`", " ").replace('"', " ").split()).strip(" .;:")
        words = [w for w in _WORD_RE.findall(text) if len(w) > 1]
        if len(words) < min_words:
            continue
        key = text.casefold()
        if key in seen_subjects:
            continue
        seen_subjects[key] = {
            "query": text,
            "category": category,
            "expected_files": answers,
            "commit": sha[:12],
        }
    return list(seen_subjects.values())


def _yaml_scalar(text: str) -> str:
    """Quote a scalar for YAML. Only double quotes and backslashes need escaping."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(records: list[dict], *, repo: Path, source: str) -> str:
    lines = [
        "# Auto-generated by tests/eval/gen_queries.py -- DO NOT EDIT BY HAND.",
        "#",
        f"# corpus: {source}",
        f"# queries: {len(records)}",
        "#",
        "# Ground truth is objective and leak-free: the query is a human-written commit",
        "# subject (git metadata, absent from the indexed corpus) and the expected files",
        "# are the files that commit actually changed. Neither side is produced by the",
        "# retriever. Regenerate after history changes; `commit` records provenance.",
        "",
    ]
    for rec in records:
        lines.append(f"- query: {_yaml_scalar(rec['query'])}")
        lines.append(f"  category: {rec['category']}")
        lines.append(f"  commit: {rec['commit']}")
        lines.append("  expected_files:")
        lines.extend(f"    - {path}" for path in rec["expected_files"])
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--repo", default=".", help="git repository to mine")
    ap.add_argument("--out", required=True, help="destination YAML path")
    ap.add_argument("--max-commits", type=int, default=4000)
    ap.add_argument(
        "--max-files",
        type=int,
        default=4,
        help="drop sweeping commits: a 60-file refactor is not a retrieval target",
    )
    ap.add_argument("--min-words", type=int, default=3)
    ap.add_argument("--limit", type=int, default=0, help="keep at most N queries (0 = all)")
    args = ap.parse_args(argv)

    repo = Path(args.repo).resolve()
    records = harvest(
        repo,
        max_commits=args.max_commits,
        max_files=args.max_files,
        min_words=args.min_words,
    )
    if args.limit > 0:
        records = records[: args.limit]
    if not records:
        print("no usable commits found", file=sys.stderr)
        return 1

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(records, repo=repo, source=repo.name), encoding="utf-8")
    print(f"wrote {len(records)} queries to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
